const messages: Record<Lang, Record<MessageKey, string>> = { ...dict, es, ja };

export function t(lang: Lang, key: MessageKey): string {
  return messages[lang][key];
}

/** Pick the field for the active UI language, with fallback. */
export function pick(
  lang: Lang,
  zh: string | null | undefined,
  en: string | null | undefined,
  localized?: Partial<Record<Lang, string | null | undefined>>,
): string {
  const direct = lang === 'zh' ? zh : lang === 'en' ? en : localized?.[lang];
  if (direct && direct.trim()) return direct.trim();
  if (lang === 'zh') return en || '';
  return (en && en.trim()) || zh || '';
}

/** Fill `{name}` style placeholders in a UI string. */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ''));
}

/**
 * Format a (possibly BCE) year. Negative years are BCE:
 * zh → 「公元前 2800」/ short 「前2800」, en → "2800 BCE".
 */
export function formatYear(lang: Lang, y: number, short = false): string {
  if (y >= 0) return String(y);
  const n = String(-y);
  if (lang === 'zh') return short ? `前${n}` : `公元前 ${n}`;
  if (lang === 'ja') return short ? `前${n}` : `紀元前${n}年`;
  if (lang === 'es') return `${n} a. C.`;
  return `${n} BCE`;
}
